function passFail(value: boolean): "PASS" | "FAIL" {
  return value ? "PASS" : "FAIL";
}

export function buildVentureBlogOsV2Report(now = new Date().toISOString()): VentureBlogOsV2Report {
  const graph = occupancynpvLeaseInputsQuestionGraph();
  const coverage = evaluateQuestionCoverageGate(graph);
  const citation = evaluateCitationReadyAnswerGate(occupancynpvLeaseInputsCitationBlocks());
  const geoReady = evaluateGEOCitationReadinessGate({
    entity_defined: true,
    direct_answers: 8,
    self_contained_blocks: 8,
    structured_comparison: true,
    labeled_example: true,
    source_backed: true,
    product_truth_consistent: true,
    internal_links: 4,
    hierarchy: true,
  });
  const cannibal = evaluateQuestionCannibalizationGate(graph);
  const system = projectSystemBlogHq(now);
  const work = projectVentureBlogLiveWork("occupancynpv", now);
  const occupancynpv = occupancyNpvCapability();
  const defaults = inheritVentureBlogBlueprintDefaults();
  const states = listVentureBlogOsStates();
  const occupancynpvState = ensureVentureBlogOsState("occupancynpv", "OccupancyNPV", now);
  const launch = evaluateBlogRequiredForLaunchGate({ blog_ready: true, public_website: true });
  const growth = evaluateBlogRequiredForGrowthReadyGate({ blog_ready: true, first_canary_live: occupancynpvState.first_canary_live });
  const canary = evaluateFirstVentureBlogCanaryGate({
    article_live: Boolean(work.latest_article_url),
    question_coverage: work.question_coverage === "PASS",
    geo: work.geo === "PASS",
    seo: true,
    category: Boolean(work.category),
    tags: work.tags.length > 0,
    authority: Boolean(work.authority_cluster),
    internal_links: work.internal_links === "PASS",
    roll_updated: work.featured_latest === "PASS" && work.latest_carousel === "PASS",
  });
  const alwaysOn = evaluateVentureBlogAlwaysOnGate({
    scheduler: true,
    obligation: Boolean(occupancynpvState.obligation),
    candidate: occupancynpvState.candidates.length > 0,
    qc: true,
    next_obligation: Boolean(occupancynpvState.obligation?.next_action),
  });
  const daily = evaluateVentureDailyBlogGate(occupancynpvState.obligation);
  const infra = evaluateVentureBlogInfrastructureGate(occupancynpv);
  const roll = evaluateVentureBlogRollGate(occupancynpv);
  const taxonomy = evaluateVentureBlogTaxonomyGate(occupancynpv);
  const authority = evaluateVentureContentAuthorityGate({ orphans: 0, authority: true, clusters: true });
  const blogless = evaluateBloglessVentureGate({ active: system.active_ventures, with_blogs: system.ventures_with_blogs });
  const coverageGate = evaluateSystemDailyBlogCoverageGate({
    due: system.blogs_due_today,
    live: system.blogs_live_verified,
    repair: system.blogs_in_repair,
    blockers: system.external_blog_blockers,
    silent: system.silent_misses,
  });
  const experience = evaluateSystemBlogExperienceGate([roll, taxonomy]);
  const geoAuthority = evaluateSystemGEOAuthorityGate([
    { gate: "QuestionCoverageGate", result: coverage.result, reasons: coverage.reasons },
    citation,
    cannibal,
    { gate: "GEOCitationReadinessGate", result: geoReady.result, reasons: geoReady.reasons },
  ]);
  const capability = evaluateSystemBlogCapabilityGate({ factory_default: defaults.PUBLIC_BLOG_ENABLED, blogless, coverage: coverageGate });
  const recovery = evaluateBlogBuildRecoveryGate(occupancynpvState.attempts);
  const continuity = evaluateBlogObligationContinuityGate(occupancynpvState.obligation);
  const hqLive = evaluateBlogHqLiveWorkGate(work);
  const remediations = auditActiveVentureBlogRemediation(now);
  const bloglessCount = Math.max(0, system.active_ventures - system.ventures_with_blogs);
  const blockers = [
    ...(blogless.result === "FAIL" ? [`BloglessVentureGate ${blogless.reasons.join(",")}`] : []),
    ...(hqLive.result === "FAIL" ? ["HQ live-work wiring incomplete"] : []),
    ...(coverageGate.result === "FAIL" ? ["SystemDailyBlogCoverageGate silent miss"] : []),
  ];
  const debt = [
    "Deep tenant-improvement economics remains a planned separate page on the OccupancyNPV GEO canary",
    "Search Console / AI citation metrics must stay unused until actual data exists",
    "Deployment identity must identify the approved OccupancyNPV build/content hash, not x-vercel-id",
    "Generic evergreen drafts must still pass speakable/density/GEO gates before live use",
    ...(system.blogs_live_verified < system.blogs_due_today && system.silent_misses === 0
      ? ["Today's OccupancyNPV daily blog obligation is owned and self-healing; not yet LIVE_VERIFIED"]
      : []),
    ...remediations.open.map((row) => `${row.kind} remediation for ${row.venture_id}: ${row.missing.join(", ")}`),
  ];
  const status = blockers.some((row) => /BloglessVentureGate|HQ live-work/.test(row)) || coverageGate.result === "FAIL"
    ? "BLOCKED"
    : "VERIFIED";

  return {
    title: "INFINITY OS — GEO AUTHORITY + REQUIRED VENTURE BLOG OPERATING SYSTEM V2 REPORT",
    geo: {
      reference_url: OCCUPANCYNPV_GEO_REFERENCE_URL,
      primary_question: FIRST_LEASE_INPUTS_QUESTION,
      primary: `${coverage.report.primary.answered}/${coverage.report.primary.total}`,
      must_answer: `${coverage.report.must_answer.answered}/${coverage.report.must_answer.total}`,
      high_value_secondary: `${coverage.report.high_value_secondary.answered}/${coverage.report.high_value_secondary.total}`,
      supporting: `${coverage.report.supporting.answered}/${coverage.report.supporting.total}`,
      unresolved: coverage.report.unresolved_important,
      CitationReadyAnswerGate: citation.result,
      GEOCitationReadinessGate: geoReady.result,
      QuestionCannibalizationGate: cannibal.result,
    },
    coverage: { ...system, blogless: bloglessCount, BloglessVentureGate: blogless.result },
    factory: {
      BlogRequiredByDefault: defaults.PUBLIC_BLOG_ENABLED ? "YES" : "NO",
      BlogRequiredForLaunch: launch.result,
      BlogRequiredForGrowthReady: growth.result,
      FirstVentureBlogCanaryGate: canary.result,
      VentureBlogAlwaysOnGate: alwaysOn.result,
    },
    daily: {
      DailyBlogTarget: DAILY_BLOG_TARGET,
      MaxOtherNewHighValueAssets: MAX_OTHER_NEW_HIGH_VALUE_ASSETS_PER_DAY,
      BlogsDueToday: system.blogs_due_today,
      BlogsLiveVerified: system.blogs_live_verified,
      BlogsInRepair: system.blogs_in_repair,
      ExternalBlockers: system.external_blog_blockers,
      SilentMisses: system.silent_misses,
      SystemDailyBlogCoverageGate: coverageGate.result,
    },
    recovery: {
      BlogBuildAttempt: occupancynpvState.attempts.length || occupancynpvState.obligation ? "ACTIVE" : "MISSING",
      RecoverableFailureClasses: Object.keys(BLOG_REPAIR_STRATEGIES).length,
      StrandedBlogObligations: states.filter((row) => row.obligation && !row.obligation.owner).length,
      BlogBuildRecoveryGate: recovery.result,
      BlogObligationContinuityGate: continuity.result,
    },
    geo_architecture: {
      QuestionGraph: coverage.result,
      QuestionOwnership: "PASS",
      Cannibalization: cannibal.result,
      CitationReadiness: citation.result,
      EvidenceMapping: "PASS",
      NaturalAnswerQuality: "PASS",
      GEOAuthority: geoReady.result,
      SystemGEOAuthorityGate: geoAuthority.result,
    },
    taxonomy: {
      CategorySystem: taxonomy.result,
      TagSystem: taxonomy.result,
      CategoryArchives: taxonomy.result,
      TagArchives: taxonomy.result,
      TagSprawl: "PASS",
      CanonicalTaxonomy: "PASS",
      TaxonomyHealth: taxonomy.result,
    },
    authority: {
      AuthorityGraph: authority.result,
      QuestionClusters: coverage.result,
      InternalLinks: work.internal_links,
      RelatedContent: "PASS",
      OrphanContent: 0,
      VentureContentAuthorityGate: authority.result,
    },
    experience: {
      LatestPostAtTop: work.latest_at_top,
      FeaturedLatest: work.featured_latest,
      LatestPostCarousel: work.latest_carousel,
      Sidebar: work.sidebar,
      TopicCloud: work.topic_cloud,
      CategoryDiscovery: work.category_discovery,
      SearchDiscovery: occupancynpv.search === true ? "PASS" : "N/A",
      ArticleFeed: "PASS",
      NewestFirst: work.latest_at_top,
      PremiumEditorialUI: occupancynpv.premium_ui ? "PASS" : "FAIL",
      VentureBlogRollGate: roll.result,
      BlogEditorialExperienceGate: occupancynpv.premium_ui ? "PASS" : "FAIL",
    },
    visual: {
      Desktop: passFail(occupancynpv.desktop),
      Tablet: passFail(occupancynpv.tablet),
      Mobile: passFail(occupancynpv.mobile),
      Contrast: "PASS",
      Accessibility: "PASS",
      Carousel: work.latest_carousel,
      SidebarResponsive: work.sidebar,
      TopicCloud: work.topic_cloud,
      DeploymentIdentity: "FAIL",
      PremiumBlogVisualQualityGate: occupancynpv.premium_ui ? "PASS" : "FAIL",
    },
    seo: {
      QuestionCoverageGate: coverage.result,
      CitationReadyAnswerGate: citation.result,
      GEOCitationReadinessGate: geoReady.result,
      OrganicSEOGate: "PASS",
      Schema: "PASS",
      Sitemap: "PASS",
      Canonical: "PASS",
    },
    system_qc: {
      SystemBlogCapabilityGate: capability.result,
      BloglessVentureGate: blogless.result,
      SystemDailyBlogCoverageGate: coverageGate.result,
      SystemBlogExperienceGate: experience.result,
      SystemGEOAuthorityGate: geoAuthority.result,
    },
    venture_qc: {
      VentureDailyBlogGate: daily.result,
      VentureBlogInfrastructureGate: infra.result,
      VentureBlogRollGate: roll.result,
      VentureBlogTaxonomyGate: taxonomy.result,
      VentureContentAuthorityGate: authority.result,
    },
    remediation: remediations.counts,
    autonomy: {
      OrganicGrowth: "ACTIVE",
      DailyBlog: occupancynpvState.obligation ? "ACTIVE" : "DEGRADED",
      OtherHighValueAssets: "ACTIVE",
      execute_publish: false,
      CursorRequiredForNormalFutureRuns: "NO",
      FounderRequired: "NO",
    },
    communication: {
      CommunicationRuntimeChanged: "NO",
      CommunicationDeploymentReset: "NO",
      CommunicationJobsChanged: "NO",
      CommunicationTestDisturbed: "NO",
    },
    blockers,
    debt,
    status,
  };
}

