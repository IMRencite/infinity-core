  seo: Record<string, NamedBlogGate["result"]>;
  system_qc: Record<string, NamedBlogGate["result"]>;
  venture_qc: Record<string, NamedBlogGate["result"]>;
  remediation: Record<string, number>;
  autonomy: Record<string, string | boolean>;
  communication: Record<string, "NO">;
  blockers: string[];
  debt: string[];
  status: "VERIFIED" | "BLOCKED";
