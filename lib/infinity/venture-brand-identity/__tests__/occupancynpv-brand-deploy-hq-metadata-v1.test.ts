import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { composeOccupancynpvPaymentReactivationFiles } from "@/lib/infinity/venture-operating-scale/occupancynpv-payment-reactivation-surface";
import { FACTORY_INHERITED_QC_CONTRACTS } from "@/lib/infinity/universal-venture-system-qc/contract";
import { INHERITED_VISUAL_AND_FAQ_QC_GATES } from "@/lib/infinity/customer-page-depth/factory";
import {
  HQ_BROWSER_TITLE,
  HQ_GLOBAL_IDENTITY,
  HQ_GLOBAL_IDENTITY_PRINCIPLE,
  hqApplicationMetadata,
  hqSelectedVentureIsOccupancynpv,
} from "@/lib/infinity/operator-console/hq-brand-context";
import { infinityOsIco, infinityOsPng } from "@/lib/infinity/operator-console/hq-brand-identity";
import { occupancynpvIco } from "@/lib/infinity/venture-operating-scale/occupancynpv-favicon";
import { evaluateOccupancynpvWorkspaceActionHierarchy } from "@/lib/infinity/customer-page-depth/app-action-hierarchy";
import {
  APPLICATION_METADATA_IDENTITY_GATE,
  evaluateApplicationMetadataIdentityGate,
  evaluateOccupancynpvBrandIdentityQc,
  factoryVentureBrandIdentityPlan,
  futureVenturesInheritBrandQc,
} from "..";
import {
  OCCUPANCYNPV_BRAND_DEPLOY_HQ_METADATA_WORK_ID,
  ensureOccupancyNpvCanonicalWork,
  listCanonicalWork,
  resetCanonicalWorkStore,
} from "@/lib/infinity/canonical-work";

describe("OccupancyNPV brand deploy + HQ metadata repair v1", () => {
  it("locks HQ as Infinity OS and fails Create Next App", () => {
    expect(HQ_GLOBAL_IDENTITY).toBe("Infinity OS");
    expect(HQ_BROWSER_TITLE).toBe("Infinity OS — HQ");
    expect(HQ_GLOBAL_IDENTITY_PRINCIPLE).toContain("HQ MUST ALWAYS IDENTIFY AS INFINITY OS");
    const layout = readFileSync("app/layout.tsx", "utf8");
    expect(layout).toContain("hqApplicationMetadata");
    expect(layout).not.toContain("Create Next App");
    expect(hqApplicationMetadata().title.default).toBe("Infinity OS — HQ");
    expect(evaluateApplicationMetadataIdentityGate({
      application_id: "infinity-os-hq",
      canonical_name: HQ_GLOBAL_IDENTITY,
      metadata_title: "Create Next App",
      metadata_description: "Generated by create next app",
    }).result).toBe("FAIL");
    expect(evaluateApplicationMetadataIdentityGate({
      application_id: "infinity-os-hq",
      canonical_name: HQ_GLOBAL_IDENTITY,
      metadata_title: HQ_BROWSER_TITLE,
      metadata_description: hqApplicationMetadata().description,
      files: [{ path: "app/layout.tsx", content: layout }],
    }).result).toBe("PASS");
  });

  it("keeps HQ favicon distinct from OccupancyNPV and selected-venture branding scoped", () => {
    expect(infinityOsIco().length).not.toBe(occupancynpvIco().length);
    expect(infinityOsPng(32).subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))).toBe(true);
    expect(hqSelectedVentureIsOccupancynpv({ ventureName: "OccupancyNPV", ventureAssemblyId: "x" })).toBe(true);
    expect(hqSelectedVentureIsOccupancynpv({ ventureName: "AskReview", ventureAssemblyId: "favc1-cycle" })).toBe(false);
    const strip = readFileSync("components/dashboard/operator-console/venture-operating-scale-strip.tsx", "utf8");
    expect(strip).toContain("hqSelectedVentureIsOccupancynpv");
    expect(strip).toContain("data-hq-selected-venture-identity");
  });

  it("inherits ApplicationMetadataIdentityGate and OccupancyNPV compose still PASSes", () => {
    expect(FACTORY_INHERITED_QC_CONTRACTS).toEqual(expect.arrayContaining([APPLICATION_METADATA_IDENTITY_GATE]));
    expect(INHERITED_VISUAL_AND_FAQ_QC_GATES).toEqual(expect.arrayContaining([APPLICATION_METADATA_IDENTITY_GATE]));
    expect(factoryVentureBrandIdentityPlan({ venture_id: "x", venture_name: "Y" }).inherited_gates)
      .toEqual(expect.arrayContaining([APPLICATION_METADATA_IDENTITY_GATE]));
    expect(futureVenturesInheritBrandQc()).toBe(true);
    const bundle = evaluateOccupancynpvBrandIdentityQc();
    expect(bundle.metadata.result).toBe("PASS");
    expect(bundle.full_pass_allowed).toBe(true);
    const composed = composeOccupancynpvPaymentReactivationFiles();
    const workspace = composed.files.find((file) => file.path.replace(/\\/g, "/") === "app/occupancynpv/app/workspaces/[id]/page.tsx")?.content ?? "";
    const css = composed.files.find((file) => file.path.replace(/\\/g, "/") === "app/occupancynpv/app/layout.tsx")?.content ?? "";
    expect(workspace).toContain("Compare NPV");
    expect(workspace).toContain("View Latest Comparison");
    expect(evaluateOccupancynpvWorkspaceActionHierarchy(workspace, css).hierarchy.result).toBe("PASS");
  });

  it("records HQ deploy/metadata work", () => {
    resetCanonicalWorkStore();
    ensureOccupancyNpvCanonicalWork();
    expect(listCanonicalWork().some((row) => row.work_id === OCCUPANCYNPV_BRAND_DEPLOY_HQ_METADATA_WORK_ID && row.status === "COMPLETED")).toBe(true);
  });
});
