import {
  APPLICATION_METADATA_IDENTITY_GATE,
  type NamedBrandGate,
} from "./contract";

const FRAMEWORK_METADATA = /create next app|generated by create next app|next\.js starter|vercel template/i;
const FRAMEWORK_ICON = /(?:^|[/"'\s])(?:next|vercel)\.svg/i;

export type ApplicationMetadataEvidence = {
  application_id: string;
  canonical_name: string;
  metadata_title?: string | null;
  metadata_description?: string | null;
  files?: Array<{ path: string; content: string; encoding?: string }>;
  live_title?: string | null;
  live_html?: string | null;
  favicon_http?: number | null;
  founder_observes_framework_default?: boolean;
};

function blob(files: ApplicationMetadataEvidence["files"] = []): string {
  return files.filter((file) => file.encoding !== "base64").map((file) => file.content).join("\n");
}

export function evaluateApplicationMetadataIdentityGate(
  input: ApplicationMetadataEvidence,
): NamedBrandGate {
  const reasons: string[] = [];
  const files = blob(input.files);
  const title = `${input.metadata_title ?? ""} ${input.live_title ?? ""}`;
  const description = input.metadata_description ?? "";
  const html = `${files}\n${input.live_html ?? ""}`;
  if (!input.canonical_name) reasons.push("CANONICAL_NAME_MISSING");
  if (!title.trim()) reasons.push("BROWSER_TITLE_MISSING");
  if (FRAMEWORK_METADATA.test(title) || FRAMEWORK_METADATA.test(description) || FRAMEWORK_METADATA.test(html)) {
    reasons.push("FRAMEWORK_DEFAULT_METADATA");
  }
  if (FRAMEWORK_ICON.test(html)) reasons.push("FRAMEWORK_DEFAULT_ICON");
  if (input.canonical_name && title.trim() && !title.includes(input.canonical_name)) {
    reasons.push("METADATA_IDENTITY_MISMATCH");
  }
  if (input.favicon_http != null && input.favicon_http !== 200) reasons.push(`FAVICON_HTTP_${input.favicon_http}`);
  if (input.founder_observes_framework_default) reasons.push("FOUNDER_PHYSICAL_FRAMEWORK_METADATA");
  return {
    gate: APPLICATION_METADATA_IDENTITY_GATE,
    result: reasons.length === 0 ? "PASS" : "FAIL",
    reasons,
  };
}
