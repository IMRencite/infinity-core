function generateCommissionTs(): string {
  return lines(
    `export type CommissionResult = { commissionCents: number; sellerPayoutCents: number };`,
    ``,
    `export function calculateCommission(amountCents: number, takeRate: number): CommissionResult {`,
    `  if (amountCents < 0) throw new Error("Amount must be non-negative");`,
    `  if (takeRate < 0 || takeRate > 1) throw new Error("Take rate must be between 0 and 1");`,
    `  const commissionCents = Math.round(amountCents * takeRate);`,
    `  const sellerPayoutCents = amountCents - commissionCents;`,
    `  return { commissionCents, sellerPayoutCents };`,
    `}`,
  );
}

