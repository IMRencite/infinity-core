async function writeGeneratedFiles(
  sandbox: VentureSandbox,
  files: string[],
  entries: Record<string, string>,
): Promise<void> {
  for (const [relativePath, content] of Object.entries(entries)) {
    await writeScaffoldFile(sandbox, files, relativePath, content);
  }
}

export async function writeMarketplaceApplication(sandbox: VentureSandbox): Promise<string[]> {
  const files: string[] = [];

  await writeScaffoldFile(sandbox, files, "package.json", generatePackageJson());
  await writeScaffoldFile(sandbox, files, "next.config.mjs", generateNextConfig());
  await writeScaffoldFile(sandbox, files, "tsconfig.json", generateTsConfig());
  await writeScaffoldFile(sandbox, files, "vitest.config.mts", generateVitestConfig());
  await writeScaffoldFile(
    sandbox,
    files,
    "next-env.d.ts",
    lines(
      `/// <reference types="next" />`,
      `/// <reference types="next/image-types/global" />`,
    ),
  );
  await writeScaffoldFile(sandbox, files, "data/store.json", generateInitialStore());
  await writeScaffoldFile(sandbox, files, "content/seo-metadata.json", generateSeoMetadata());
  await writeScaffoldFile(sandbox, files, "lib/db/store.ts", generateStoreTs());
  await writeScaffoldFile(sandbox, files, "lib/auth/password.ts", generateAuthPasswordTs());
  await writeScaffoldFile(sandbox, files, "lib/auth/session.ts", generateAuthSessionTs());
  await writeScaffoldFile(sandbox, files, "lib/api/helpers.ts", generateApiHelpersTs());
  await writeScaffoldFile(sandbox, files, "lib/marketplace/commission.ts", generateCommissionTs());
  await writeScaffoldFile(sandbox, files, "lib/marketplace/transactions.ts", generateTransactionsTs());
  await writeScaffoldFile(sandbox, files, "lib/marketplace/analytics.ts", generateAnalyticsTs());
  await writeScaffoldFile(sandbox, files, "lib/marketplace/entitlements.ts", generateEntitlementsTs());
  await writeScaffoldFile(sandbox, files, "middleware.ts", generateMiddlewareTs());

  await writeGeneratedFiles(sandbox, files, generateAuthApiRoutes());
  await writeGeneratedFiles(sandbox, files, generateContentApiRoutes());
  await writeGeneratedFiles(sandbox, files, generateMarketplaceApiRoutes());
  await writeGeneratedFiles(sandbox, files, generateComponents());
  await writeGeneratedFiles(sandbox, files, generatePages());
  await writeGeneratedFiles(sandbox, files, generateTests());

  return files;
}
