export function publicPageArchetype(archetype: PublicPageArchetype): PublicPageArchetypeDefinition {
  return { archetype, inheritsGlobalContract: true, ...DEFINITIONS[archetype] };
}

export function publicPageArchetypeRegistry() {
  return {
    model: "PublicPageArchetypeRegistry" as const,
    version: "V1" as const,
    archetypes: PUBLIC_PAGE_ARCHETYPES.map(publicPageArchetype),
    templatesAreFixedLayouts: false as const,
  };
}

export function archetypeSpecializesGlobalContract(archetype: PublicPageArchetype): boolean {
  const definition = publicPageArchetype(archetype);
  return definition.inheritsGlobalContract && definition.outcomes.length > 0;
}
