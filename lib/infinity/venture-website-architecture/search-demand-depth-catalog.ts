export function assertDepthCatalogLocks() {
  const routes = new Set(DEPTH_QUESTION_PAGES.map((page) => page.route));
  const mapped = new Set(Object.values(DEPTH_STANDALONE_ROUTES));
  if (routes.size !== DEPTH_QUESTION_PAGES.length) throw new Error("depth_catalog_duplicate_route");
  if (routes.size !== mapped.size) throw new Error("depth_catalog_route_mismatch");
  for (const page of DEPTH_QUESTION_PAGES) {
    if (DEPTH_STANDALONE_ROUTES[page.clusterId] !== page.route) throw new Error(`depth_cluster_drift:${page.clusterId}`);
  }
}
