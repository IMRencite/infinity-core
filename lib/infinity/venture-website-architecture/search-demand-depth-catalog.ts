export type DepthQuestionPage = {
  route: string;
  hub: string;
  topic: TopicId;
  clusterId: string;
  question: string;
  slug: string;
  title: string;
  description: string;
  semanticIntent: SemanticIntent;
  searchIntent: SearchIntent;
  discoveryGroup: "START_HERE" | "CALCULATE_IT" | "COMPARE_OPTIONS" | "COMMON_MISTAKES" | "GO_DEEPER" | "FOR_YOUR_ROLE";
  cta: { href: string; label: string };
  midCta: { href: string; label: string };
  finalCta: { href: string; label: string };
};

function page(
  clusterId: keyof typeof DEPTH_STANDALONE_ROUTES | string,
  extra: Omit<DepthQuestionPage, "route" | "hub" | "topic" | "clusterId" | "slug">,
): DepthQuestionPage {
  const route = DEPTH_STANDALONE_ROUTES[clusterId];
  if (!route) throw new Error(`depth_route_missing:${clusterId}`);
  const parts = route.split("/").filter(Boolean);
  return {
    route,
    hub: `/${parts[0]}`,
    topic: parts[0] as TopicId,
    clusterId,
    slug: parts[1] ?? "",
    ...extra,
  };
}

