export function pageOpportunityId(ventureId: string, topic: string, route: string): string {
  return `pop_${createHash("sha256").update([ventureId, topic, route].join("|")).digest("hex").slice(0, 16)}`;
}

function unknownSearch(query: string, relevance: SearchOpportunity["relevance"], evidence: string): SearchOpportunity {
  return { query, volumeState: "UNKNOWN", volume: null, relevance, evidence };
}

function geo(question: string, entityFocus: string, answerability: GeoOpportunity["answerability"] = "HIGH"): GeoOpportunity {
  return { question, answerability, entityFocus, volumeState: "UNKNOWN" };
}

