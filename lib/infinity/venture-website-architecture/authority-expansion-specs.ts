function years(startRent: number, cam: number, creditY1: number, bump: number, notes: string[]): YearRow[] {
  return notes.map((note, index) => ({
    rent: Math.round(startRent * (1 + bump) ** index),
    cam: Math.round(cam * 1.03 ** index),
    credit: index === 0 ? creditY1 : 0,
    note,
  }));
}

function pageOf(route: string): ExpansionQuestionPage {
  const row = EXPANSION_QUESTION_PAGES.find((item) => item.route === route);
  if (!row) throw new Error(`expansion_page_missing:${route}`);
  return row;
}

function spec(
  route: string,
  extra: Omit<ExpansionPageSpec, "route" | "question" | "cta" | "midCta" | "finalCta">,
): ExpansionPageSpec {
  const page = pageOf(route);
  return {
    route,
    question: page.question,
    cta: page.cta,
    midCta: page.midCta,
    finalCta: page.finalCta,
    ...extra,
  };
}

