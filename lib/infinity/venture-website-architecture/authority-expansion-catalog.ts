export function plannedExpansionQuestionPage(page: ExpansionQuestionPage): PlannedPage {
  return {
    route: page.route,
    role: "QUESTION_PAGE",
    primaryIntent: page.searchIntent === "COMMERCIAL_INVESTIGATION" ? "COMPARISON" : "DEFINITIONAL",
    parentHub: page.hub,
    title: page.title,
    metaDescription: page.description,
    canonical: page.route.endsWith("/") ? page.route : `${page.route}/`,
    indexable: true,
    schemaTypes: ["WebPage", "Article", "BreadcrumbList", "FAQPage"],
    patternId: "DEEP_AUTHORITY_QUESTION_PAGE",
    ctaStrength: "CONTEXTUAL",
    topicCluster: page.topic,
    pageOpportunityId: `opp_${page.slug}`,
  };
}

export function allExpansionQuestionPages(): ExpansionQuestionPage[] {
  return EXPANSION_QUESTION_PAGES;
}

export function expansionPageFile(route: string): string {
  const clean = route.replace(/\/+$/, "");
  return `app${clean}/page.tsx`;
}

export function expansionRouteCount(predecessorRouteCount: number): number {
  return predecessorRouteCount + newStandaloneRoutes().length;
}

export function allExpansionPlannedPages(): PlannedPage[] {
  return EXPANSION_QUESTION_PAGES.map(plannedExpansionQuestionPage);
}
